def journal_pdf():
    title = "面向学术论文的自动评分方法研究"
    text_parts = [
        title,
        "摘要：自动论文评分（AES）是教育测量的重要课题。本文提出一种基于大语言模型与评分量规的多维度评分方法，"
        "将评分任务分解为逐维度证据定位与加权汇总两个阶段，在自建中文课程论文数据集上与人工评分的一致性达到QWK 0.81。",
        "关键词：自动评分；大语言模型；评分量规",
        "1 引言：论文评分工作量大且主观性强。现有AES方法多针对短作文训练专用模型，泛化能力受限，且难以给出可解释的评分依据。"
        "本文探索以通用大语言模型为核心、以量规为约束的评分框架，目标是兼顾准确性、可解释性与跨学科可迁移性。",
        "2 方法：系统包括文本解析、维度评分与汇总三个模块。维度评分阶段，模型针对每个评分维度独立输出分数、置信度与原文证据；"
        "汇总阶段按权重加权得到总分。针对超长论文，采用分块要点提炼以适配上下文长度。",
        "3 实验：数据集包含300篇研究生课程论文，由两名教师独立评分。实验表明，逐维度评分相比整体直接打分，"
        "与人工评分的QWK从0.68提升到0.81；证据引用使教师复核时间缩短约40%。消融实验验证了量规约束与两阶段设计的有效性。",
        "4 结论与局限：量规约束下的多阶段大模型评分能够逼近人工评分水平并提供可解释依据。局限在于样本量有限、领域覆盖不足，"
        "且对高度专业化的学科内容仍需专家复核。",
        "References: [1] Ke Z et al. Automated Essay Scoring. 2024. [2] Xiao C et al. Human-AI Collaborative Essay Scoring. LAK 2025.",
    ]
    doc = fitz.open()
    page = doc.new_page()
    rect = page.rect
    y = 60
    for part in text_parts:
        inserted = 0
        while inserted < len(part):
            page.insert_text((60, y), part[inserted:inserted + 42], fontsize=11, fontname="china-s")
            y += 18
            inserted += 42
            if y > rect.height - 50:
                page = doc.new_page()
                y = 60
        y += 10
    doc.save(SAMPLES / "期刊论文样例_自动评分方法研究.pdf")
    doc.close()


