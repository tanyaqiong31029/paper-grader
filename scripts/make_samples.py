def make_docx(path, title, blocks):
    d = docx.Document()
    d.add_heading(title, level=0)
    for kind, text in blocks:
        if kind == "h":
            d.add_heading(text, level=1)
        elif kind == "p":
            d.add_paragraph(text)
    d.save(path)


